import "server-only"

import type { Slicer, SliceInput, SliceResult } from "@/src/adapters/slicer"
import type { AssetStorage } from "@/src/adapters/storage"
import { getPrinterProfile, getStrengthPreset } from "@/src/config/profiles"
import { appError } from "@/src/lib/errors"
import { err, ok, type Result } from "@/src/lib/result"

/**
 * Filesystem + process seam for the real PrusaSlicer CLI. The concrete Node
 * implementation (child_process + fs/tmp) lives in `nodeRuntime.ts` and is the
 * only coverage-excluded slicer file; everything here is exercised with a fake.
 */
export interface PrusaRuntime {
  writeTempMesh(bytes: Uint8Array): Promise<{ inputPath: string; outputPath: string }>
  run(command: string, args: string[]): Promise<Result<void>>
  readGcode(path: string): Promise<Result<string>>
  cleanup(paths: string[]): Promise<void>
}

export interface PrusaStats {
  durationMinutes: number
  materialGrams: number
  materialMeters: number
  supportsUsed: boolean
  slicerVersion: string
}

/** Build the PrusaSlicer CLI arguments (pure, unit-tested). */
export function buildPrusaArgs(
  input: SliceInput,
  paths: { profilePath: string; inputPath: string; outputPath: string }
): string[] {
  const strength = getStrengthPreset(input.strengthId)
  const fillDensity = strength === undefined ? 20 : strength.infillPct
  return [
    "--load",
    paths.profilePath,
    "--scale",
    String(input.scaleFactor),
    "--fill-density",
    `${fillDensity}%`,
    "--support-material",
    "--export-gcode",
    "--output",
    paths.outputPath,
    paths.inputPath,
  ]
}

const HMS_RE = /;\s*estimated printing time \(normal mode\)\s*=\s*(.+)/i
const GRAMS_RE = /;\s*(?:total )?filament used \[g\]\s*=\s*([\d.]+)/i
const MM_RE = /;\s*(?:total )?filament used \[mm\]\s*=\s*([\d.]+)/i
const SUPPORT_RE = /;\s*support_material\s*=\s*1\b/i
const VERSION_RE = /;\s*generated by PrusaSlicer\s*([\w.-]+)/i

/** Parse "1h 23m 45s" / "23m 5s" / "45s" into whole minutes (rounded up). */
export function parsePrintTimeMinutes(text: string): number {
  const h = /(\d+)\s*h/i.exec(text)
  const m = /(\d+)\s*m/i.exec(text)
  const s = /(\d+)\s*s/i.exec(text)
  const seconds =
    (h === null ? 0 : Number(h[1]) * 3600) +
    (m === null ? 0 : Number(m[1]) * 60) +
    (s === null ? 0 : Number(s[1]))
  return Math.ceil(seconds / 60)
}

/** Extract slice stats from PrusaSlicer's gcode comment block (pure, unit-tested). */
export function parsePrusaSliceStats(gcode: string): Result<PrusaStats> {
  const time = HMS_RE.exec(gcode)
  const grams = GRAMS_RE.exec(gcode)
  const mm = MM_RE.exec(gcode)
  if (time === null || grams === null || mm === null) {
    return err(appError("provider_error", "could not parse slice stats from gcode"))
  }
  const version = VERSION_RE.exec(gcode)
  return ok({
    durationMinutes: parsePrintTimeMinutes(time[1] as string),
    materialGrams: Number(grams[1]),
    materialMeters: Number(mm[1]) / 1000,
    supportsUsed: SUPPORT_RE.test(gcode),
    slicerVersion: `prusa-slicer/${version === null ? "unknown" : (version[1] as string)}`,
  })
}

/** Real PrusaSlicer CLI slicer (SLICER=prusa). I/O runs through the injected runtime. */
export class PrusaSlicerCli implements Slicer {
  constructor(
    private readonly deps: {
      storage: AssetStorage
      runtime: PrusaRuntime
      slicerPath: string
      profileDir: string
    }
  ) {}

  async slice(input: SliceInput): Promise<Result<SliceResult>> {
    const mesh = await this.deps.storage.read(input.meshStorageKey)
    if (!mesh.ok) return mesh

    const tmp = await this.deps.runtime.writeTempMesh(mesh.value)
    const profilePath = `${this.deps.profileDir}/${input.printerProfileId}.ini`
    const args = buildPrusaArgs(input, { profilePath, inputPath: tmp.inputPath, outputPath: tmp.outputPath })

    const cleanup = (): Promise<void> => this.deps.runtime.cleanup([tmp.inputPath, tmp.outputPath])

    const ran = await this.deps.runtime.run(this.deps.slicerPath, args)
    if (!ran.ok) {
      await cleanup()
      return ran
    }
    const gcode = await this.deps.runtime.readGcode(tmp.outputPath)
    if (!gcode.ok) {
      await cleanup()
      return gcode
    }
    const stats = parsePrusaSliceStats(gcode.value)
    if (!stats.ok) {
      await cleanup()
      return stats
    }

    const stored = await this.deps.storage.put(new TextEncoder().encode(gcode.value), {
      keyPrefix: "gcode",
      mime: "text/x.gcode",
    })
    await cleanup()
    if (!stored.ok) return stored

    return ok({
      durationMinutes: stats.value.durationMinutes,
      materialGrams: stats.value.materialGrams,
      materialMeters: stats.value.materialMeters,
      supportsUsed: stats.value.supportsUsed,
      gcodeStorageKey: stored.value.storageKey,
      slicerVersion: stats.value.slicerVersion,
      profileVersion: getPrinterProfile(input.printerProfileId).version,
      orientation: { rx: 0, ry: 0, rz: 0 },
    })
  }
}
